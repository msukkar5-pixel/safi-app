"""Builds app/src/main/assets/deen/*.json.
Needs DEEN_SRC = folder with ara-{bukhari,muslim,abudawud,tirmidhi,nasai,ibnmajah}.json (fawazahmed0/hadith-api),
quran.json (fawazahmed0/quran-api ara-quransimple) and hisn.json (asellam/HisnElMuslim, MIT).
Fails if any hadith quote isn't found in the book it's attributed to."""
import json, os, sys, re
from urllib.parse import quote
import lib, c_umrah, c_hajj, c_ruqyah

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "app", "src", "main", "assets", "deen")
os.makedirs(OUT, exist_ok=True)

def dump(name, obj):
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, separators=(",", ":"))

guides = [c_umrah.build(), c_hajj.build(), c_ruqyah.build()]
if lib.ERR:
    print("\n".join(lib.ERR)); sys.exit(1)
for g in guides:
    dump(g["id"] + ".json", g)
    print(g["id"], len(g["sections"]), "sections", sum(len(s["blocks"]) for s in g["sections"]), "blocks")

# ---------------------------------------------------------------- Hisn al-Muslim
GROUPS = [(1, 14, "اليوم والبيت والمسجد", "🏠"), (15, 26, "الصلاة", "🕌"), (27, 34, "الصباح والمساء والنوم", "🌅"),
          (35, 47, "الهم والكرب والشدائد", "🤲"), (48, 61, "المرض والمصائب والجنائز", "🌿"), (62, 68, "المطر والرياح والهلال", "🌧️"),
          (69, 77, "الطعام والصيام", "🍽️"), (78, 95, "الآداب والمعاملات", "🤝"), (96, 106, "السفر", "✈️"),
          (107, 115, "متفرقات", "📿"), (116, 122, "الحج والعمرة", "🕋"), (123, 133, "الذكر والاستغفار والتسبيح", "✨")]
src = json.load(open(os.path.join(os.environ["DEEN_SRC"], "hisn.json"), encoding="utf-8"))
chapters = []
for i, (title, v) in enumerate(src.items(), 1):
    items = []
    for a in v["Adhkar"]:
        t = re.sub(r"\s+", " ", a["Text"]).strip()
        items.append({"x": t, "n": int(a.get("Count") or 1), "ref": (a.get("Reference") or "").strip()})
    g = next(k for k, (a, b, _, _) in enumerate(GROUPS) if a <= i <= b)
    chapters.append({"i": i, "t": title.strip(), "g": g, "audio": v.get("Audio", ""), "items": items})
dump("hisn.json", {"title": "حصن المسلم", "author": "سعيد بن علي بن وهف القحطاني",
                   "note": "من أذكار الكتاب والسنة. النص المشكول وتخريج كل ذكر كما في الكتاب، والتسجيلات الصوتية من موقع طريق الإسلام.",
                   "groups": [{"t": t, "icon": ic} for (_, _, t, ic) in GROUPS], "chapters": chapters})
print("hisn", len(chapters), "chapters", sum(len(c["items"]) for c in chapters), "adhkar")

