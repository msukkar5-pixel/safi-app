    fun match(text: String): Destination? {
        val normalized = text.lowercase()
        return destinations.maxByOrNull { d -> d.keywords.count { it in normalized } }?.takeIf { d -> d.keywords.any { it in normalized } }
    }

    fun wantsOpen(text: String): Boolean {
        val normalized = text.lowercase()
        return listOf("افتح", "روح", "وديني", "دخلني", "روحني", "انتقل", "هات", "اظهر", "أظهر").any { it in normalized }
    }

    fun asksHow(text: String): Boolean {
        val normalized = text.lowercase()
        return listOf("ازاي", "إزاي", "كيف", "اعمل", "استخدم", "طريقة", "خطوات").any { it in normalized }
    }

    fun localReply(text: String): String? = match(text)?.takeIf { wantsOpen(text) || asksHow(text) }?.let { d ->
        (if (wantsOpen(text)) "هفتح لك «${d.title}» الآن.\n\n" else "") + d.steps
    }

    fun prompt(): String = destinations.joinToString("\n") { "- ${it.route}: ${it.title}. ${it.steps}" }
}
